"""T-19: a gated run and the operator checkout are different environments.

`git worktree add` copies tracked files only, so gated runs have no `.env`/`node_modules`/`.venv`.
The T-9 merge was green at the gate and red locally because a collection-time app import loaded
the operator's `.env`. These offline tests prove that class is closed.
"""

