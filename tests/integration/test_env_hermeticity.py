import os

from orchestrator.api.main import app  # noqa: F401 - importing it executes create_app()
from orchestrator.core.config import get_settings


def test_collection_time_app_import_cannot_poison_the_suite():
    settings = get_settings()
    assert settings.supabase_url is None
    assert settings.supabase_publishable_key is None
    assert settings.supabase_sync_enabled is False
