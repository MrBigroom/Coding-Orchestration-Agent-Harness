def _project(session, tmp_path: Path, name: str, *, with_env: bool, suite: str = RUN_TESTS):
    repo = make_repo(tmp_path / name, {"run_tests.py": suite, "README.md": "x\n"})
    if with_env:
        env_text = SEEDED_ENV if suite is RUN_TESTS else "SYNTHETIC_PARITY=present\n"
        (repo / ".env").write_text(env_text)
    return project_service.create(
        session,
        ProjectCreate(name=name, path=str(repo), base_branch="main",
                      test_command="python3 run_tests.py"),
    )


def _verify_in(session, project, short_id: str):
    task = task_service.create(
        session,
        TaskCreate(title="T-19 environment evidence", project_id=project.id,
                   phase_number=1, phase_slug="env",
                   definition_of_done=["environment recorded"]),
    )
    run = Run(short_id=short_id, task_id=task.id, status="testing",
              worktree_path=project.path, branch_name="main")
    session.add(run)
    session.commit()
    session.refresh(run)
    handoff = Handoff(phase="1", branch="main", status="READY_FOR_REVIEW",
                      summary="environment evidence",
                      tests=HandoffTests(command="python3 run_tests.py", passed=2))
    result = asyncio.run(supervisor_service.verify(session, task, run, project, handoff, False))
    return run, {check.name: check for check in result.checks}


def _saved_check(run, name: str) -> dict:
    saved = json.loads(artifact_service.read_text(run.id, "verification.json"))
    return {check["name"]: check for check in saved["checks"]}[name]


def test_verification_json_names_the_gated_environment(session, tmp_path):
    """DoD 3: existing evidence says which world produced the green; no field/artifact added."""
    run, checks = _verify_in(
        session, _project(session, tmp_path, "clean-world", with_env=False), "R-T19-CLEAN"
    )
    assert checks["tests"].status == "pass"
    assert "environment:" in checks["tests"].evidence
    assert "local .env absent" in checks["tests"].evidence
    # An ordinary checkout is not a tracked-files-only worktree and must not be labelled one.
    assert "tracked-files-only worktree" not in checks["tests"].evidence
    saved = _saved_check(run, "tests")
    assert "local .env absent" in saved["evidence"]
    assert set(saved) == {"name", "status", "command", "evidence", "notes"}

    linked = tmp_path / "linked"
    linked.mkdir()
    (linked / ".git").write_text("gitdir: /tmp/main/.git/worktrees/linked\n")
    assert "tracked-files-only worktree" in project_service.environment_summary(linked)

    run, checks = _verify_in(
        session, _project(session, tmp_path, "env-world", with_env=True), "R-T19-ENV"
    )
    assert "local .env present" in checks["tests"].evidence
    assert "local .env present" in _saved_check(run, "tests")["evidence"]


def test_doctor_env_parity_seeds_the_local_env_and_removes_the_tree(session, tmp_path):
    """DoD 4: the opt-in developer check runs the suite with a copy of the local `.env`."""
    project = _project(session, tmp_path, "parity-proj", with_env=True, suite=CHECK_SEEDED_ENV)
    assert not [
        c for c in project_service.doctor(project) if c["name"].startswith("env-parity")
    ]  # off by default
    checks = {c["name"]: c for c in project_service.doctor(project, env_parity=True)}
    assert checks["env-parity .env seeded"]["ok"] is True
    assert checks["env-parity suite"]["ok"] is True, checks["env-parity suite"]
    assert "local .env seeded" in checks["env-parity suite"]["detail"]
    assert "SYNTHETIC_PARITY" not in checks["env-parity .env seeded"]["detail"]
    assert git_service.managed_worktrees() == []

    no_env = _project(session, tmp_path, "no-env-proj", with_env=False)
    result = {c["name"]: c for c in project_service.doctor(no_env, env_parity=True)}
    assert result["env-parity suite"]["ok"] is True
    assert "nothing to seed" in result["env-parity suite"]["detail"]
    assert git_service.managed_worktrees() == []


def test_env_parity_reports_a_leftover_worktree_instead_of_sweeping_it(session, tmp_path):
    """A killed run's seeded worktree is T-20 residue hygiene: T-19 only reports it."""
    project = _project(session, tmp_path, "stale-proj", with_env=False)
    info = git_service.ensure_snapshot(
        Path(project.path), project.slug, project_service.ENV_PARITY_SNAPSHOT_KEY,
        project.base_branch,
    )
    seeded = info.path / ".env"
    seeded.write_text(SEEDED_ENV)
    checks = {c["name"]: c for c in project_service.doctor(project, env_parity=True)}
    assert checks["env-parity stale worktree"]["ok"] is False
    assert "orchestrator cleanup" in checks["env-parity stale worktree"]["detail"]
    assert seeded.exists()  # not swept: that is T-20, explicitly out of scope here
    # This test created the residue; remove it so the throwaway home stays clean.
    leftover = next(
        m
        for m in git_service.managed_worktrees()
        if m["task_id"] == project_service.ENV_PARITY_SNAPSHOT_KEY
    )
    seeded.unlink()
    git_service.remove_worktree(Path(project.path), leftover, dry_run=False)


def test_env_parity_reports_a_preexisting_dotenv_instead_of_raising(session, tmp_path):
    """A repo that TRACKS `.env` already has one in the snapshot: doctor reports, never raises.

    Round-4 finding 4: `_seeded_env_copy` used to open the destination with `O_EXCL`, so the
    `FileExistsError` escaped `doctor()` and broke this module's "reports, never raises" rule.
    """
    original = "SYNTHETIC_PARITY=tracked\n"
    repo = make_repo(
        tmp_path / "tracked-env", {"run_tests.py": RUN_TESTS, ".env": original}
    )
    project = project_service.create(
        session,
        ProjectCreate(name="tracked-env", path=str(repo), base_branch="main",
                      test_command="python3 run_tests.py"),
    )
    checks = {c["name"]: c for c in project_service.doctor(project, env_parity=True)}
    assert checks["env-parity .env seeded"]["ok"] is False
    assert "FileExistsError" in checks["env-parity .env seeded"]["detail"]
    assert "env-parity suite" not in checks  # nothing was run against an unseeded tree
    # The operator's own file is never the copy destination and is left untouched.
    assert (repo / ".env").read_text() == original
    assert git_service.managed_worktrees() == []


def test_env_parity_never_unlinks_a_dotenv_it_did_not_create(session, tmp_path, monkeypatch):
    """Round-4 finding 4: cleanup is scoped to the file THIS invocation created.

    The old finally block unlinked `info.path / ".env"` even when the copy had failed, deleting a
    pre-existing file and leaving the tree tracked-dirty. Keep the throwaway tree (patch out the
    snapshot drop) so the foreign file is observable after `doctor()` returns.
    """
    original = "SYNTHETIC_PARITY=tracked\n"
    repo = make_repo(
        tmp_path / "foreign-env", {"run_tests.py": RUN_TESTS, ".env": original}
    )
    project = project_service.create(
        session,
        ProjectCreate(name="foreign-env", path=str(repo), base_branch="main",
                      test_command="python3 run_tests.py"),
    )
    monkeypatch.setattr(project_service, "_drop_snapshots", lambda *a, **k: None)
    checks = {c["name"]: c for c in project_service.doctor(project, env_parity=True)}
    assert checks["env-parity .env seeded"]["ok"] is False
    leftover = next(
        m
        for m in git_service.managed_worktrees()
        if m["task_id"] == project_service.ENV_PARITY_SNAPSHOT_KEY
    )
    seeded = leftover["path"] / ".env"
    assert seeded.read_text() == original
    # The unique staging name is cleaned up on the failure path too: no residue in the tree.
    assert list(leftover["path"].glob(".env.*.parity")) == []
    # This test created the snapshot; remove it so the throwaway home stays clean.
    note = git_service.remove_worktree(Path(project.path), leftover, dry_run=False)
    assert note.startswith("removed"), note
    assert git_service.managed_worktrees() == []


