def _project(session, tmp_path: Path, name: str, *, with_env: bool, suite: str = RUN_TESTS):
    repo = make_repo(tmp_path / name, {"run_tests.py": suite, "README.md": "x\n"})
    if with_env:
        env_text = SEEDED_ENV if suite is RUN_TESTS else "SYNTHETIC_PARITY=present\n"
        (repo / ".env").write_text(env_text)
    return project_service.create(
        session,
        ProjectCreate(name=name, path=str(repo), base_branch="main",
                      test_command="python3 run_tests.py"),
    )


def _verify_in(session, project, short_id: str):
    task = task_service.create(
        session,
        TaskCreate(title="T-19 environment evidence", project_id=project.id,
                   phase_number=1, phase_slug="env",
                   definition_of_done=["environment recorded"]),
    )
    run = Run(short_id=short_id, task_id=task.id, status="testing",
              worktree_path=project.path, branch_name="main")
    session.add(run)
    session.commit()
    session.refresh(run)
    handoff = Handoff(phase="1", branch="main", status="READY_FOR_REVIEW",
                      summary="environment evidence",
                      tests=HandoffTests(command="python3 run_tests.py", passed=2))
    result = asyncio.run(supervisor_service.verify(session, task, run, project, handoff, False))
    return run, {check.name: check for check in result.checks}


def _saved_check(run, name: str) -> dict:
    saved = json.loads(artifact_service.read_text(run.id, "verification.json"))
    return {check["name"]: check for check in saved["checks"]}[name]


